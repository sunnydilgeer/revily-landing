export function isScienceSubject(value: unknown): value is ScienceSubject {
  return value === 'biology' || value === 'chemistry' || value === 'physics'
}
export function scienceSubjectTitle(subject: ScienceSubject) {
  return subject === 'biology' ? 'Biology' : subject === 'chemistry' ? 'Chemistry' : 'Physics'
}
export function scienceLessonsFor(subject: ScienceSubject): readonly ScienceCatalogueEntry[] {
  return scienceSubjects.find(item => item.subject === subject)?.lessons ?? []
}
export function scienceChaptersFor(subject: ScienceSubject): readonly ScienceChapter[] {
  return scienceSubjects.find(item => item.subject === subject)?.chapters ?? []
}
export function getScienceLesson(subject: ScienceSubject, number: number): ScienceCatalogueEntry | null {
  return scienceLessonsFor(subject).find(item => item.number === number) ?? null
}
export function scienceEntryById(id: string): ScienceCatalogueEntry | null {
  return allScienceLessons.find(item => item.lesson.id === id) ?? null
}
